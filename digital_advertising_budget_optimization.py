def before_after_figure(rep):
    rec, B = rep["rec"].sort_values("Recommended_%", ascending=False), rep["budget"]
    top = max(rec["Current_Budget"].max(), rec["Recommended_Budget"].max()) * 1.18
    fig, ax = plt.subplots(1, 2, figsize=(13, 4.4), sharey=True)
    for a, col, title, shade in [(ax[0], "Current_Budget", "BEFORE — current spending mix", "#B0BEC5"),
                                 (ax[1], "Recommended_Budget", "AFTER — recommended spending", "#17365D")]:
        a.bar(rec.index, rec[col], color=shade)
        a.set_title(title); a.set_ylim(0, top); a.set_xlabel("")
        for x, (name, v) in enumerate(rec[col].items()):
            a.text(x, v + top * 0.015, f"Rs. {v/1000:,.0f}k", ha="center", fontsize=9)
    ax[0].set_ylabel("Rs.")
    fig.suptitle(f"Allocation of {rs(B)}  ·  expected revenue {rs(rep['rev_before'])} → {rs(rep['rev_after'])}  ({rep['uplift_pct']:+.1f}%)", y=1.02)
    plt.tight_layout()
    return fig

