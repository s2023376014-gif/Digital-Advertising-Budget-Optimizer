def generate_campaign_data(n, seed=CONFIG["seed"]):
    # Vectorised generator. One row = campaign x day x audience segment.
    rng = np.random.default_rng(seed)
    day      = rng.integers(0, N_DAYS, n)
    plat     = rng.choice(len(PLATFORMS), n, p=PARAMS["share_of_records"].values)
    camp     = rng.integers(0, len(CAMPAIGNS), n)
    gender   = rng.choice(2, n, p=GENDER_P)
    city     = rng.choice(len(CITIES), n, p=CITY_P)
    device   = rng.choice(len(DEVICES), n, p=DEVICE_P)
    age      = np.empty(n, dtype=np.int64)
    for k in range(len(PLATFORMS)):
        m = plat == k
        age[m] = rng.choice(4, int(m.sum()), p=AGE_P[k])

    impressions = np.clip(rng.lognormal(np.log(15_000), 0.7, n), 500, 400_000).astype(np.int64)

    ctr = (PARAMS["ctr"].values[plat] * AGE_ENG[plat, age] * DEV_CTR[device]
           * (1 + PARAMS["ctr_drift"].values[plat] * (day / N_DAYS - 0.5)))
    clicks = rng.binomial(impressions, np.clip(ctr, 0.0005, 0.25))

    saturation = (impressions / 15_000.0) ** (-PARAMS["saturation"].values[plat])
    weekend    = ((START.dayofweek + day) % 7) >= 5
    cvr = (PARAMS["cvr"].values[plat] * GEN_CVR[gender] * CITY_CVR[city] * DEV_CVR[device]
           * SEASON[day] * (1 + 0.08 * weekend) * CAMP_MULT[camp] * saturation)
    conversions = rng.binomial(clicks, np.clip(cvr, 0.0005, 0.5))       # always <= clicks

    spend = np.round(impressions * PARAMS["cpm"].values[plat] / 1000 * rng.lognormal(0, 0.08, n)).astype(np.int64)
    aov   = PARAMS["aov"].values[plat] * AGE_AOV[age] * GEN_AOV[gender] * rng.lognormal(0, 0.25, n)
    revenue = np.round(conversions * aov).astype(np.int64)

    return pd.DataFrame({
        "date":        START + pd.to_timedelta(day, unit="D"),
        "campaign":    pd.Categorical.from_codes(camp, CAMPAIGNS),
        "brand":       pd.Categorical.from_codes(CAMPAIGN_BRAND[camp], BRANDS),
        "platform":    pd.Categorical.from_codes(plat, PLATFORMS),
        "impressions": impressions.astype(np.int32),
        "clicks":      clicks.astype(np.int32),
        "spend":       spend,                       # whole rupees -> exact integer sums at any scale
        "conversions": conversions.astype(np.int32),
        "revenue":     revenue,
        "age":         pd.Categorical.from_codes(age, AGES),
        "gender":      pd.Categorical.from_codes(gender, GENDERS),
        "city":        pd.Categorical.from_codes(city, CITIES),
        "device":      pd.Categorical.from_codes(device, DEVICES),
    })

