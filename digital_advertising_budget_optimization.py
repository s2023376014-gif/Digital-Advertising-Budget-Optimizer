"""### How to read the benchmark
* **Pandas** is vectorised C code on one machine; as long as the data fits in RAM it is very hard to beat.
* **MapReduce (pure Python)** touches every record in a Python loop, so its time grows linearly with data — this is exactly why Hadoop-style MapReduce needs a *cluster* of machines to pay off.
* **Spark** pays a fixed start-up/scheduling cost, so it loses on small data, but it scales gracefully: its curve is the flattest, it keeps working when the data no longer fits in memory, and on a multi-node cluster the work is split across machines.
* **Take-away for management:** on this laptop-sized job Pandas is the right tool; Spark becomes the right tool when the data grows beyond one machine (hundreds of millions of rows, or many files in a data lake). The point of the experiment is to see *where the crossover begins*, and the trend lines above show it.
* Absolute times depend on the machine (CPU cores, Colab vs laptop) — the **shape** of the curves is what matters.

## 6. Marketing Budget Recommendation Engine
The engine learns from the **1,000,000-record simulated history** and answers: *how should the next Rs. 1,000,000 be split?*

**Method (explainable on purpose)**
1. Compute platform KPIs from the history (CTR, CVR, CPA, ROAS).
2. Estimate **diminishing returns**: fit `revenue = a · spend^b` per platform. If `b < 1`, each extra rupee earns less than the average rupee did, so the engine also rewards **marginal ROAS = b × ROAS**.
3. Score each platform: `Score = 0.35·ROAS + 0.20·Marginal ROAS + 0.20·CPA(inverse) + 0.15·CVR + 0.10·CTR`, each metric expressed as a fraction of the best platform (weights are in `CONFIG`).
4. Convert scores to shares, then apply **guard-rails** (min 5 %, max 40 %) so a single platform can never take the whole budget — real media plans always keep some diversification and test budget.
5. Round to whole percentages that sum to exactly 100.
"""

