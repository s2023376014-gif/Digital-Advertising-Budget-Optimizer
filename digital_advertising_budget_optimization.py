def fit_elasticity(df, bins=25):
    out = {}
    for p, g in df.groupby("platform", observed=True):
        g = g[(g["spend"] > 0) & (g["revenue"] > 0)]
        if len(g) < 250:                                   # too little data to fit a curve -> assume no saturation
            out[p] = 1.0; continue
        q = pd.qcut(g["spend"], bins, duplicates="drop")
        b = g.groupby(q, observed=True).agg(spend=("spend", "mean"), revenue=("revenue", "mean"))
        if len(b) < 3:
            out[p] = 1.0; continue
        slope = np.polyfit(np.log(b["spend"]), np.log(b["revenue"]), 1)[0]      # slope = elasticity b
        out[p] = float(np.clip(slope, 0.3, 1.0))
    return pd.Series(out)

