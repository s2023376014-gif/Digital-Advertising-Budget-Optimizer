def make_dashboard():
    out = widgets.Output()
    busy = {"on": False}
    ws = {}

    def build_controls(df):
        months = sorted(df["date"].dt.strftime("%Y-%m").unique())
        sel = lambda col, lab, r=4: widgets.SelectMultiple(options=list(df[col].cat.categories), value=tuple(df[col].cat.categories),
                                                           description=lab, rows=r, layout=widgets.Layout(width="230px"))
        ws.update(platform=sel("platform", "Platform", 5), brand=sel("brand", "Brand"), age=sel("age", "Age"), gender=sel("gender", "Gender", 3))
        ws["m0"] = widgets.Dropdown(options=months, value=months[0], description="From")
        ws["m1"] = widgets.Dropdown(options=months, value=months[-1], description="To")

    build_controls(STATE["df"])
    ws["budget"] = widgets.BoundedIntText(value=1_000_000, min=10_000, max=10**10, step=50_000, description="Budget Rs.")
    presets = [widgets.Button(description=f"Rs. {v:,}") for v in (500_000, 1_000_000, 2_000_000)]
    for b, v in zip(presets, (500_000, 1_000_000, 2_000_000)):
        b.on_click(lambda _b, v=v: setattr(ws["budget"], "value", v))
    btn_csv, btn_pdf = widgets.Button(description="Download CSV", button_style="primary"), widgets.Button(description="Download PDF", button_style="primary")
    upload = widgets.FileUpload(accept=".csv", multiple=False, description="Upload your CSV")
    status = widgets.HTML(f"<i>Data: {STATE['source']}</i>")
    last = {"rep": None}

    def current_args():
        return dict(budget=int(ws["budget"].value), platforms=list(ws["platform"].value), brands=list(ws["brand"].value),
                    ages=list(ws["age"].value), genders=list(ws["gender"].value), date_from=ws["m0"].value, date_to=ws["m1"].value)

    def refresh(_=None):
        if busy["on"]: return
        with out:
            out.clear_output(wait=True)
            if ws["m0"].value > ws["m1"].value:
                print("'From' month must not be after 'To' month."); return
            last["rep"] = dashboard_report(STATE["df"], **current_args())
            show_report(last["rep"])

    def save(kind):
        with out:
            if last["rep"] is None:
                print("Nothing to download for these filters."); return
            f = save_report_csv if kind == "csv" else save_report_pdf
            download(f(last["rep"], OUT_DIR / f"budget_recommendation.{kind}"))

    btn_csv.on_click(lambda _b: save("csv")); btn_pdf.on_click(lambda _b: save("pdf"))

    def on_upload(change):
        v = upload.value
        if not v: return
        item = v[0] if isinstance(v, (tuple, list)) else list(v.values())[0]
        try:
            df = load_real_data(BytesIO(bytes(item["content"])))
        except Exception as e:
            status.value = f"<span style='color:#c0392b'>Could not use file: {e}</span>"; return
        STATE.update(df=df, source=f"Uploaded: {item['name']}")
        busy["on"] = True
        build_controls(df)
        box.children = layout_children()
        busy["on"] = False
        status.value = f"<b style='color:#1b8a4b'>Loaded {len(df):,} rows from {item['name']}</b>"
        observe(); refresh()
    upload.observe(on_upload, names="value")

    def observe():
        for k in ("platform", "brand", "age", "gender", "m0", "m1", "budget"):
            ws[k].observe(refresh, names="value")

    def layout_children():
        return [widgets.HBox([ws["platform"], ws["brand"], ws["age"], ws["gender"]]), widgets.HBox([ws["m0"], ws["m1"]]),
                widgets.HBox([ws["budget"], *presets, btn_csv, btn_pdf]), widgets.HBox([upload, status]), out]

    box = widgets.VBox(layout_children())
    observe(); refresh()
    return box

