    rec = rec.copy()
    rec["Current_Budget"] = rec["Current_spend_%"] / 100 * budget
    rec["Change_Rs"]      = rec["Recommended_Budget"] - rec["Current_Budget"]
    before = float((rec["Current_Budget"] * rec["ROAS"]).sum())
    after  = float((rec["Recommended_Budget"] * rec["ROAS"]).sum())
    return {"sub": sub, "rec": rec, "perf": perf, "budget": budget, "rev_before": before, "rev_after": after,
            "uplift_pct": (after / before - 1) * 100 if before else 0.0,
            "filters": describe_filters(df, platforms, brands, ages, genders, date_from, date_to)}

