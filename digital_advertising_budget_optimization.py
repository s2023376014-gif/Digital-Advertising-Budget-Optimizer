"""## 4. Marketing KPIs & campaign performance

| KPI | Formula | Meaning |
|---|---|---|
| **CTR** | clicks ÷ impressions × 100 | how attractive the ad is |
| **CPC** | spend ÷ clicks | price of one visit |
| **CPA** | spend ÷ conversions | price of one customer / sale |
| **Conversion rate (CVR)** | conversions ÷ clicks × 100 | how well visits turn into sales |
| **ROAS** | revenue ÷ spend | rupees earned per rupee spent |

> **Important:** for groups of rows (a platform, a campaign …) KPIs are computed from the *summed* numbers (total clicks ÷ total impressions). Averaging row-level ratios would give small campaigns the same weight as big ones and bias the result.
"""

METRICS = ["impressions", "clicks", "spend", "conversions", "revenue"]

def sdiv(a, b):
    # Safe division: returns NaN instead of inf when the denominator is 0.
    a, b = np.asarray(a, dtype=float), np.asarray(b, dtype=float)
    return np.where(b > 0, a / np.where(b > 0, b, 1), np.nan)

def add_kpis(d):
    d = d.copy()
    d["CTR_%"] = sdiv(d["clicks"], d["impressions"]) * 100
    d["CPC"]   = sdiv(d["spend"], d["clicks"])
    d["CPA"]   = sdiv(d["spend"], d["conversions"])
    d["CVR_%"] = sdiv(d["conversions"], d["clicks"]) * 100
    d["ROAS"]  = sdiv(d["revenue"], d["spend"])
    return d

def kpi_table(df, by):
    # Aggregate first, then derive KPIs from the totals.
    g = df.groupby(by, observed=True)[METRICS].sum().reset_index()
    g = add_kpis(g)
    g["spend_share_%"]   = g["spend"]   / g["spend"].sum()   * 100
    g["revenue_share_%"] = g["revenue"] / g["revenue"].sum() * 100
    return g

